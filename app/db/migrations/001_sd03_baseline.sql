-- F1 운영자 계정 (FR-051 · Key Entities 운영자 계정)
CREATE TABLE IF NOT EXISTS operator_account (
  operator_id     BIGINT        NOT NULL AUTO_INCREMENT,
  login_id        VARCHAR(64)   NOT NULL,
  password_hash   VARCHAR(255)  NOT NULL,          -- 복원 불가 형태(해시 방식 미정)
  display_name    VARCHAR(100)  NOT NULL,
  created_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  disabled_at     TIMESTAMP(3)  NULL,
  CONSTRAINT pk_operator_account PRIMARY KEY (operator_id),
  CONSTRAINT uq_operator_login UNIQUE (login_id),
  -- BR-OPS-07: 개인 운영자 계정만(빈 아이디·빈 해시 금지)
  CONSTRAINT chk_operator_nonempty CHECK (TRIM(login_id) <> '' AND TRIM(password_hash) <> '')
);

-- F2 처리 설정 판본 (H5 · UC10 · BR-OPS-02·06·09)
--   한 판본 = 저장 버튼 한 번. 요청은 접수 시점의 판본을 참조한다(BR-OPS-02 "이후 요청부터").
CREATE TABLE IF NOT EXISTS processing_setting_version (
  setting_version_id          BIGINT        NOT NULL AUTO_INCREMENT,
  created_at                  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  created_by                  BIGINT        NOT NULL,
  timeout_seconds             INT           NULL,   -- 처리 시간 제한(값 미정)
  max_concurrency             INT           NULL,   -- 동시 처리 상한(값 미정)
  fallback_enabled            BOOLEAN       NOT NULL DEFAULT TRUE,  -- 끌 수 있게 할지 미정(미해결 #1)
  default_call_limit_per_day  INT           NULL,   -- 새 키 기본 호출 한도(값 미정)
  apply_rate_limit_count      INT           NULL,   -- 신청 빈도 제한: 창 안 허용 건수(값 미정)
  apply_rate_window_minutes   INT           NULL,   -- 신청 빈도 제한: 창 길이(값 미정)
  structure_threshold         DECIMAL(5,4)  NULL,   -- 구조 확인 기준값(값 미정, 척도 [추론] 0~1)
  grade_caution_boundary      DECIMAL(5,4)  NULL,   -- 이 값 미만이면 주의(값 미정)
  grade_distrust_boundary     DECIMAL(5,4)  NULL,   -- 이 값 미만이면 불신(값 미정)
  api_apply_status            VARCHAR(12)   NOT NULL DEFAULT 'pending',
  api_applied_at              TIMESTAMP(3)  NULL,
  CONSTRAINT pk_setting_version PRIMARY KEY (setting_version_id),
  CONSTRAINT fk_setting_operator FOREIGN KEY (created_by) REFERENCES operator_account (operator_id),
  -- G6 운영 값 검증 (UC10 E2 · UC14 E1 [추론] "0·음수 금지")
  CONSTRAINT chk_g6_timeout      CHECK (timeout_seconds > 0),
  CONSTRAINT chk_g6_concurrency  CHECK (max_concurrency >= 1),
  CONSTRAINT chk_g6_default_limit CHECK (default_call_limit_per_day >= 1),
  CONSTRAINT chk_g6_rate_count   CHECK (apply_rate_limit_count >= 1),
  -- G6 + BR-KEY-06: 신청 내용은 7일 뒤 지워지므로 7일(10080분)보다 긴 창은 판정할 자료가 없다
  CONSTRAINT chk_g6_rate_window  CHECK (apply_rate_window_minutes BETWEEN 1 AND 10080),
  CONSTRAINT chk_g6_structure    CHECK (structure_threshold BETWEEN 0 AND 1),
  -- G6 (UC10 E8 [추론]): 주의 경계가 불신 경계보다 엄격해야 한다(불신 < 주의)
  CONSTRAINT chk_g6_grade_range  CHECK (grade_caution_boundary BETWEEN 0 AND 1
                                        AND grade_distrust_boundary BETWEEN 0 AND 1),
  CONSTRAINT chk_g6_grade_order  CHECK (grade_distrust_boundary < grade_caution_boundary),
  -- UC10 E5: 반영 상태는 셋 중 하나, 반영됨이면 반영 시각이 있다
  CONSTRAINT chk_setting_apply   CHECK (api_apply_status IN ('pending','applied','unapplied')),
  CONSTRAINT chk_setting_applied_at CHECK ((api_apply_status = 'applied' AND api_applied_at IS NOT NULL)
                                        OR (api_apply_status <> 'applied' AND api_applied_at IS NULL))
);

-- F3 엔진 호출 순서 (BR-ENG-02 · BR-OPS-06 오선보·정간보 각각)
CREATE TABLE IF NOT EXISTS setting_engine_order (
  setting_version_id  BIGINT       NOT NULL,
  score_type          VARCHAR(12)  NOT NULL,
  seq                 SMALLINT     NOT NULL,
  engine_name         VARCHAR(40)  NOT NULL,
  CONSTRAINT pk_setting_engine_order PRIMARY KEY (setting_version_id, score_type, seq),
  CONSTRAINT uq_setting_engine_once UNIQUE (setting_version_id, score_type, engine_name),
  CONSTRAINT fk_engine_order_version FOREIGN KEY (setting_version_id)
    REFERENCES processing_setting_version (setting_version_id) ON DELETE CASCADE,
  CONSTRAINT chk_engine_order_type CHECK (score_type IN ('staff','jeongganbo')),
  CONSTRAINT chk_engine_order_seq  CHECK (seq >= 1)
);

-- F4 라이선스 정책 (G7 · BR-RND-03·06 · SD_01 §11-2 "라이선스 확인 여부 플래그")
CREATE TABLE IF NOT EXISTS license_policy (
  policy_code   VARCHAR(40)   NOT NULL,
  confirmed     BOOLEAN       NOT NULL DEFAULT FALSE,
  decided_by    BIGINT        NULL,
  decided_at    TIMESTAMP(3)  NULL,
  CONSTRAINT pk_license_policy PRIMARY KEY (policy_code),
  CONSTRAINT fk_license_operator FOREIGN KEY (decided_by) REFERENCES operator_account (operator_id),
  CONSTRAINT chk_license_code CHECK (policy_code IN ('sound_and_renderer')),
  -- G7 해제 기록: 확인됨으로 바꾼 사람과 시각이 있어야 한다
  CONSTRAINT chk_license_decided CHECK (confirmed = FALSE OR (decided_by IS NOT NULL AND decided_at IS NOT NULL))
);

-- 원천 사실: 라이선스는 아직 확인되지 않았다(BR-RND-03·06). 행이 없을 때만 넣는다(멱등).
INSERT INTO license_policy (policy_code, confirmed)
SELECT 'sound_and_renderer', FALSE FROM (SELECT 1 AS one) AS seed
 WHERE NOT EXISTS (SELECT 1 FROM license_policy WHERE policy_code = 'sound_and_renderer');



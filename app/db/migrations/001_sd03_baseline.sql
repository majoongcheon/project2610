-- D1 악기 (BR-PLY-03 국악기 먼저 · FR-023 · C4)
CREATE TABLE IF NOT EXISTS instrument (
  instrument_id   BIGINT       NOT NULL AUTO_INCREMENT,
  name            VARCHAR(60)  NOT NULL,     -- MusicXML 에 글자로 적는 이름(BR-EDT-06)
  family          VARCHAR(10)  NOT NULL,
  midi_program    SMALLINT     NULL,         -- 국악기 표기 방법 미정(UC_00 미해결 18)
  range_low       SMALLINT     NULL,         -- 연주 가능 음역 아래(MIDI 음번호, 값 미정) — S2 음역 경고(BR-EDT-03)
  range_high      SMALLINT     NULL,         -- 연주 가능 음역 위(값 미정)
  is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
  CONSTRAINT pk_instrument PRIMARY KEY (instrument_id),
  CONSTRAINT uq_instrument_name UNIQUE (name),
  CONSTRAINT chk_instrument_family CHECK (family IN ('gugak','other')),
  CONSTRAINT chk_instrument_program CHECK (midi_program BETWEEN 0 AND 127),
  CONSTRAINT chk_instrument_range CHECK (range_low BETWEEN 0 AND 127 AND range_high BETWEEN 0 AND 127
                                      AND range_low <= range_high)
);

-- D2 악기 구성 (기본 국악기 구성 · 추천 조합 · 원래 악기 · API 직접 지정)
CREATE TABLE IF NOT EXISTS ensemble (
  ensemble_id     BIGINT       NOT NULL AUTO_INCREMENT,
  ensemble_kind   VARCHAR(12)  NOT NULL,
  created_at      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  -- BR-PLY-01: 기본 국악기 구성은 하나뿐이다. default 행에만 1, 나머지는 NULL 이 되어 UNIQUE 가 하나만 허용한다.
  default_marker  SMALLINT GENERATED ALWAYS AS (CASE WHEN ensemble_kind = 'default' THEN 1 ELSE NULL END) STORED,
  CONSTRAINT pk_ensemble PRIMARY KEY (ensemble_id),
  CONSTRAINT uq_ensemble_single_default UNIQUE (default_marker),
  CONSTRAINT chk_ensemble_kind CHECK (ensemble_kind IN ('default','recommended','original','custom'))
);

-- D3 악기 구성의 파트
CREATE TABLE IF NOT EXISTS ensemble_member (
  ensemble_id               BIGINT        NOT NULL,
  part_no                   SMALLINT      NOT NULL,
  part_role                 VARCHAR(12)   NULL,   -- 선율·타악(예: "선율 가야금·타악 장구")
  instrument_id             BIGINT        NULL,
  original_instrument_name  VARCHAR(100)  NULL,   -- 올린 MIDI·MusicXML 에 적힌 악기(BR-PLY-04)
  original_midi_program     SMALLINT      NULL,
  CONSTRAINT pk_ensemble_member PRIMARY KEY (ensemble_id, part_no),
  CONSTRAINT fk_member_ensemble FOREIGN KEY (ensemble_id) REFERENCES ensemble (ensemble_id) ON DELETE CASCADE,
  CONSTRAINT fk_member_instrument FOREIGN KEY (instrument_id) REFERENCES instrument (instrument_id),
  CONSTRAINT chk_member_part CHECK (part_no >= 1),
  CONSTRAINT chk_member_role CHECK (part_role IN ('melody','percussion','other')),
  -- 서비스 악기이거나 원래 악기이거나 둘 중 하나
  CONSTRAINT chk_member_one_source CHECK ((instrument_id IS NOT NULL AND original_instrument_name IS NULL)
                                       OR (instrument_id IS NULL AND original_instrument_name IS NOT NULL)),
  CONSTRAINT chk_member_program CHECK (original_midi_program BETWEEN 0 AND 127)
);



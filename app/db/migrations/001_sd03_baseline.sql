  FROM api_spec_snapshot p
 WHERE p.snapshot_id = (SELECT MAX(snapshot_id) FROM api_spec_snapshot);

-- 엔드포인트 목록 = 마지막으로 정상 확인한 명세(서버가 멈춰도 "마지막 확인본"을 보인다, UC11 E2)

-- =====================================================================
-- 영역 E. API 접근 키·호출 (쓰기 주체: 웹 서비스(신청)·운영자(폐기·한도)·모델 API 서버(호출 기록))
--         생애: 키는 영구, 신청 내용은 7일(보관 처리 시 계속)
-- =====================================================================

-- E1 접근 키 (H6 · BR-KEY-01~05 · FR-053·055) — 키 원문 컬럼은 두지 않는다(BR-KEY-05 · G9)
CREATE TABLE IF NOT EXISTS access_key (
  key_id              BIGINT        NOT NULL AUTO_INCREMENT,
  key_kind            VARCHAR(10)   NOT NULL,
  key_hash            VARCHAR(255)  NOT NULL,   -- 해시 방식 미정
  key_prefix          VARCHAR(16)   NOT NULL,   -- 앞 몇 글자(글자 수 미정)
  application_no      VARCHAR(20)   NULL,       -- 외부 키의 신청 번호. 신청 내용이 지워져도 남는다
  call_limit_per_day  INT           NULL,
  issued_at           TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  issued_by           BIGINT        NULL,       -- 서비스 전용 키만 운영자가 발급(UC14 A2)
  status              VARCHAR(8)    NOT NULL DEFAULT 'active',
  revoked_at          TIMESTAMP(3)  NULL,
  revoked_by          BIGINT        NULL,
  CONSTRAINT pk_access_key PRIMARY KEY (key_id),
  CONSTRAINT uq_access_key_hash UNIQUE (key_hash),
  CONSTRAINT uq_access_key_application UNIQUE (application_no),
  CONSTRAINT fk_key_issued_by FOREIGN KEY (issued_by) REFERENCES operator_account (operator_id),
  CONSTRAINT fk_key_revoked_by FOREIGN KEY (revoked_by) REFERENCES operator_account (operator_id),
  CONSTRAINT chk_key_kind CHECK (key_kind IN ('external','service')),
  -- BR-KEY-01: 외부 키는 신청으로 자동 발급(운영자 없음), 서비스 전용 키는 신청 없이 운영자가 발급
  CONSTRAINT chk_key_origin CHECK ((key_kind = 'external' AND application_no IS NOT NULL AND issued_by IS NULL)
                                OR (key_kind = 'service'  AND application_no IS NULL AND issued_by IS NOT NULL)),
  -- BR-KEY-03 · G6: 외부 키는 한도가 반드시 있고 1 이상. 서비스 전용 키의 한도 적용 여부는 미정(미해결)
  CONSTRAINT chk_key_limit CHECK (call_limit_per_day >= 1),
  CONSTRAINT chk_key_limit_required CHECK (key_kind = 'service' OR call_limit_per_day IS NOT NULL),
  -- BR-KEY-02: 상태 머신 — 사용 중이면 폐기 정보가 없고, 폐기면 시각과 처리 운영자가 있다
  CONSTRAINT chk_key_status CHECK ((status = 'active'  AND revoked_at IS NULL AND revoked_by IS NULL)
                                OR (status = 'revoked' AND revoked_at IS NOT NULL AND revoked_by IS NOT NULL))
);

-- E2 접근 키 신청 내용 (H7 · BR-KEY-06·07 · FR-060·061) — 키 기록과 따로 두고 7일 뒤 행을 지운다
CREATE TABLE IF NOT EXISTS key_application (
  key_id           BIGINT         NOT NULL,
  applicant_name   VARCHAR(100)   NOT NULL,
  affiliation      VARCHAR(200)   NOT NULL,
  contact_email    VARCHAR(254)   NOT NULL,
  purpose          VARCHAR(1000)  NOT NULL,
  applied_at       TIMESTAMP(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  consent_given    BOOLEAN        NOT NULL,
  client_address   VARCHAR(45)    NOT NULL,   -- G11 "같은 접속 주소" 판정용. 신청 내용과 함께 지워진다
  retained_at      TIMESTAMP(3)   NULL,       -- 보관 처리(7일 자동 삭제에서 뺌)
  retained_by      BIGINT         NULL,
  CONSTRAINT pk_key_application PRIMARY KEY (key_id),
  CONSTRAINT fk_application_key FOREIGN KEY (key_id) REFERENCES access_key (key_id),
  CONSTRAINT fk_application_retained_by FOREIGN KEY (retained_by) REFERENCES operator_account (operator_id),
  -- G10 신청 필수 항목(UC15 E1): 네 항목이 비어 있지 않다
  CONSTRAINT chk_g10_required CHECK (TRIM(applicant_name) <> '' AND TRIM(affiliation) <> ''
                                  AND TRIM(contact_email) <> '' AND TRIM(purpose) <> ''),
  -- G10 + BR-KEY-07: 개인정보 수집·이용 동의 없이는 저장하지 않는다
  CONSTRAINT chk_g10_consent CHECK (consent_given = TRUE),
  -- BR-KEY-06: 보관 처리는 시각과 처리 운영자가 함께 있다
  CONSTRAINT chk_application_retained CHECK ((retained_at IS NULL AND retained_by IS NULL)
                                          OR (retained_at IS NOT NULL AND retained_by IS NOT NULL))
);



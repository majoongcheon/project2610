--
-- 작성 규약
--   * 표준 SQL 을 기본으로 한다. 검증 DBMS 는 MariaDB 12.0.2 이다.
--   * DBMS 전용 구문은 쓰는 자리에 [MariaDB] 주석으로 이유를 남긴다.
--     공통으로 쓰는 것은 여기에 한 번만 적는다.
--       [MariaDB] AUTO_INCREMENT      — 표준 GENERATED BY DEFAULT AS IDENTITY 를 MariaDB 가 지원하지 않는다.
--       [MariaDB] TIMESTAMPDIFF()     — 표준 (a - b) 기간 연산을 MariaDB 가 지원하지 않는다.
--       [MariaDB] CREATE OR REPLACE VIEW / TRIGGER — 멱등 실행용. 표준에는 OR REPLACE 가 없다.
--       [MariaDB] CREATE INDEX IF NOT EXISTS       — 멱등 실행용. 표준에는 IF NOT EXISTS 가 없다.
--       [MariaDB] DELIMITER           — mariadb 클라이언트 지시어(트리거 본문의 ; 처리). SQL 문이 아니다.
--       [MariaDB] 트리거 본문의 IF/SIGNAL — SQL/PSM(표준 9075-4) 형식이다. 제품마다 문법 차이가 있다.
--   * 생성 순서는 FK 의존 위상 순서다(참조되는 테이블이 먼저).
--   * 재실행해도 실패하지 않는다(IF NOT EXISTS · OR REPLACE · NOT EXISTS 가드).
--   * 업무규칙 구현 제약에는 어느 BR/게이트의 구현인지 주석을 단다.
--   * 원천에 값이 없는 임계값·기간은 지어내지 않는다. 컬럼은 두고 NULL(미정)을 허용한다.
--     원천에 값이 있는 상수(24시간, 7일, 20MB, 800px, .sf2 50MB, 세션당 3개)만 제약·뷰에 넣는다.
--
-- 논리 설계와 달라진 점(실행 중 이탈 기록)
--   D1. 설정 변경 이력 뷰(v_setting_change_history)의 엔진 순서 비교에 GROUP_CONCAT 을 썼다.
--       표준은 LISTAGG 이나 MariaDB 가 지원하지 않는다.
--   D3. 검증 중 발견: "col IN (...)" 조건은 col 이 NULL 이면 UNKNOWN 이 되어 CHECK 를 통과한다.
--       이미지인데 종류 없음 · 이유 없는 대체 · 종류 없는 진짜 평가 악보가 받아들여졌다. IS NOT NULL 을 더해 막았다.
--   D2. 트리거는 뷰를 읽어 판정한다(G4 는 v_request_retention). 판정식을 트리거에 다시 쓰지 않기 위해서다.
--       그래서 뷰를 테이블 뒤, 트리거 앞에 만든다.

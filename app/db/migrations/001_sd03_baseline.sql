-- A1 익명 세션 (spec Assumptions 사용자와 접근 · UC8 세션 단위)
CREATE TABLE IF NOT EXISTS anon_session (
  session_id      CHAR(36)      NOT NULL,     -- 앱이 만든 무작위 식별자
  started_at      TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  last_active_at  TIMESTAMP(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  ended_at        TIMESTAMP(3)  NULL,         -- 세션 종료 판정 기준은 미정(UC8 E4)
  CONSTRAINT pk_anon_session PRIMARY KEY (session_id),
  CONSTRAINT chk_session_time CHECK (ended_at IS NULL OR ended_at >= started_at)
);

-- A2 악보 요청 (Key Entities 악보 요청 · H1·H4 · UC3 사후조건 ①)
CREATE TABLE IF NOT EXISTS score_request (
  request_id          BIGINT        NOT NULL AUTO_INCREMENT,
  request_no          VARCHAR(20)   NOT NULL,   -- 화면·API 요청 번호(예: R-0928-0012). 발급 뒤 바뀌지 않는다
  channel             VARCHAR(4)    NOT NULL,   -- 요청 경로

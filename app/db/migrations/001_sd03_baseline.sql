CREATE OR REPLACE VIEW v_request_queue_position AS
SELECT r.request_id,
       (SELECT COUNT(*) FROM score_request q
         WHERE q.status = 'queued' AND q.received_at <= r.received_at) AS queue_position
  FROM score_request r
 WHERE r.status = 'queued';

-- G8 세션당 사용자 음원 3개 — 단일 판정 지점(BR-SF2-02). S2 [음원 올리기] 비활성과 트리거가 함께 읽는다
CREATE OR REPLACE VIEW v_session_soundfont_count AS
SELECT s.session_id,
       (SELECT COUNT(*) FROM user_soundfont f
         WHERE f.session_id = s.session_id AND f.file_deleted_at IS NULL) AS active_count,
       CASE WHEN (SELECT COUNT(*) FROM user_soundfont f
                   WHERE f.session_id = s.session_id AND f.file_deleted_at IS NULL) >= 3
            THEN 0 ELSE 1 END                                             AS can_upload
  FROM anon_session s;

-- G11 신청 빈도 제한 — 단일 판정 지점(FR-061 · UC15 E2). "다시 신청할 수 있는 시각"도 여기서 낸다
--   같은 연락 이메일 또는 같은 접속 주소 기준. 값이 미정(NULL)이면 행이 없어 제한하지 않는다
CREATE OR REPLACE VIEW v_apply_rate_window AS
SELECT x.rate_key,
       COUNT(*)                                                           AS recent_count,
       s.apply_rate_limit_count                                           AS limit_count,
       MIN(x.applied_at) + INTERVAL s.apply_rate_window_minutes MINUTE    AS next_allowed_at,
       CASE WHEN COUNT(*) >= s.apply_rate_limit_count THEN 1 ELSE 0 END   AS is_blocked
  FROM (SELECT CONCAT('email:', a.contact_email)  AS rate_key, a.applied_at FROM key_application a
        UNION ALL
        SELECT CONCAT('addr:', a.client_address) AS rate_key, a.applied_at FROM key_application a) x
  CROSS JOIN v_current_setting s
 WHERE s.apply_rate_limit_count IS NOT NULL
   AND s.apply_rate_window_minutes IS NOT NULL
   AND x.applied_at > CURRENT_TIMESTAMP(3) - INTERVAL s.apply_rate_window_minutes MINUTE
 GROUP BY x.rate_key, s.apply_rate_limit_count, s.apply_rate_window_minutes;

-- 서버 상태 = 마지막 확인본 (S4-A 레일 "서버 상태" · S6 서버 상태 줄 · UC11 E2·E3 · UC9 A3·E4)

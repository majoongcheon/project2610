-- S4-B 발급된 키 목록 — 신청 내용이 7일 뒤 지워졌는지(UC14 E6 "이미 삭제된 신청")
CREATE OR REPLACE VIEW v_key_admin_list AS
SELECT k.key_id, k.key_kind, k.key_prefix, k.call_limit_per_day, k.issued_at, k.status, k.application_no,
       CASE WHEN k.key_kind = 'external' AND a.key_id IS NULL THEN 1 ELSE 0 END AS application_purged
  FROM access_key k
  LEFT JOIN key_application a ON a.key_id = k.key_id;

-- G4 보관 기간 — 단일 판정 지점 (BR-RET-01 24시간). 화면·API·트리거·P0 가 모두 이 뷰를 읽는다
CREATE OR REPLACE VIEW v_request_retention AS
SELECT r.request_id,
       r.request_no,
       r.received_at,
       r.received_at + INTERVAL '24' HOUR                                        AS expires_at,
       GREATEST(0, TIMESTAMPDIFF(SECOND, CURRENT_TIMESTAMP(3), r.received_at + INTERVAL '24' HOUR))
                                                                                 AS remaining_seconds,
       CASE WHEN r.purged_at IS NOT NULL
              OR CURRENT_TIMESTAMP(3) >= r.received_at + INTERVAL '24' HOUR
            THEN 1 ELSE 0 END                                                    AS is_expired
  FROM score_request r;

-- P0 삭제 대상 (0.1): 만료되었지만 아직 지우지 않은 요청
CREATE OR REPLACE VIEW v_purge_due_requests AS
SELECT v.request_id, v.request_no, v.expires_at
  FROM v_request_retention v
  JOIN score_request r ON r.request_id = v.request_id
 WHERE r.purged_at IS NULL
   AND CURRENT_TIMESTAMP(3) >= v.expires_at;

-- 처리 단계 표시 (C1 처리 단계 · UC13 6단계 상태 값) — 웹과 API 의 낱말을 한 곳에서 정한다
CREATE OR REPLACE VIEW v_request_stage_label AS
SELECT r.request_id,
       r.channel,
       CASE
         WHEN r.status = 'received'             THEN '접수'
         WHEN r.status = 'queued'               THEN '대기'
         WHEN r.status = 'converting'           THEN '변환 중'
         WHEN r.status = 'awaiting_type_answer' THEN '종류 확인'
         WHEN r.status = 'rendering'            THEN '연주 생성'
         WHEN r.status = 'service_down'         THEN '서비스 중단'
         WHEN r.route = 'fallback'              THEN CASE WHEN r.channel = 'api' THEN '대체 완료' ELSE '대체' END
         ELSE '완료'
       END AS stage_label,
       CASE
         WHEN r.status <> 'completed'  THEN NULL
         WHEN r.route = 'fallback'     THEN '대체 결과로 완료'
         WHEN r.route = 'direct'       THEN '직행 결과로 완료'
         ELSE '완료'
       END AS completion_label,
       -- C3 결과 상태 띠: 신뢰 · 주의 · 대체 · 직행
       CASE
         WHEN r.status <> 'completed' THEN NULL
         WHEN r.route = 'fallback'    THEN 'fallback'
         WHEN r.route = 'direct'      THEN 'direct'
         WHEN j.validity_grade = 'caution' THEN 'caution'
         ELSE 'trust'
       END AS result_band
  FROM score_request r
  LEFT JOIN processing_job j ON j.request_id = r.request_id;

